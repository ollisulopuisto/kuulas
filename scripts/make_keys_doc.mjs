#!/usr/bin/env node
// Generate docs/KEYS.md from ui/keymap-default.js and the English locale.
// Run with: node scripts/make_keys_doc.mjs [output_path]

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { setCatalogs, t } from "../ui/i18n.js";

const __dirname = dirname(fileURLToPath(import.meta.url));

const keymapModule = await import(new URL("../ui/keymap-default.js", import.meta.url));
const { DEFAULT_KEYMAP, CONTEXTS } = keymapModule;

const en = JSON.parse(
  readFileSync(resolve(__dirname, "../src/kuulas/locales/en.json"), "utf8"),
);

// Command references use their labels here: one reference serves both platform columns.
setCatalogs({ en });

const outPath = process.argv[2] || resolve(__dirname, "../docs/KEYS.md");

const MAC_MODS = { Mod: "⌘", Alt: "⌥", Shift: "⇧", Ctrl: "⌃" };
const OTHER_MODS = { Mod: "Ctrl", Alt: "Alt", Shift: "Shift", Ctrl: "Ctrl" };

function formatCombo(combo, mods) {
  return combo
    .split("+")
    .map((part) => mods[part] || (part === "Comma" ? "," : part))
    .join("+");
}

function formatEntryKeys(keys, mods) {
  if (keys === null || keys === undefined) {
    return "";
  }
  if (Array.isArray(keys)) {
    return keys.map((combo) => formatCombo(combo, mods)).join(" or ");
  }
  return formatCombo(keys, mods);
}

function escapeCell(text) {
  return text.replace(/\|/g, "\\|");
}

function hasKeys(entry) {
  const keys = entry.keys;
  if (!keys) {
    return false;
  }
  return keys.mac !== null || keys.other !== null;
}

const lines = [];
lines.push("# Keyboard shortcuts");
lines.push("");
lines.push("This file is generated by `node scripts/make_keys_doc.mjs`. Do not edit it by hand.");
lines.push("");

let boundCount = 0;

for (const context of CONTEXTS) {
  const entries = DEFAULT_KEYMAP
    .filter((entry) => entry.context === context && hasKeys(entry))
    .sort((a, b) => a.id.localeCompare(b.id));

  if (entries.length === 0) {
    continue;
  }

  const contextLabel = en[`keys.context.${context}`] || context;
  lines.push(`## ${contextLabel}`);
  lines.push("");
  lines.push("| Key (Mac) | Key (Windows/Linux) | Command | What it does |");
  lines.push("| --- | --- | --- | --- |");

  for (const entry of entries) {
    const mac = formatEntryKeys(entry.keys.mac, MAC_MODS);
    const other = formatEntryKeys(entry.keys.other, OTHER_MODS);
    const label = escapeCell(en[entry.labelKey] ? t(entry.labelKey) : "");
    const hint = escapeCell(en[`${entry.labelKey}.hint`] ? t(`${entry.labelKey}.hint`) : "");
    lines.push(`| ${mac} | ${other} | ${label} | ${hint} |`);
    boundCount += 1;
  }

  lines.push("");
}

lines.push(`Total bound commands: ${boundCount}`);

writeFileSync(outPath, lines.join("\n"), "utf8");
