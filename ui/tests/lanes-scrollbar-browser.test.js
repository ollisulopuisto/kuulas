// Real-browser regression for the timeline scroll indicator and waveform stacking.
import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { createServer } from "node:http";
import { extname, join, normalize } from "node:path";
import { after, before, test } from "node:test";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const run = promisify(execFile);
const ui = fileURLToPath(new URL("..", import.meta.url));
const chrome = [
  process.env.CHROME,
  "/usr/bin/google-chrome",
  "/usr/bin/chromium",
  "/usr/bin/chromium-browser",
  "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
].find((path) => path && existsSync(path));
const types = { ".html": "text/html", ".js": "text/javascript", ".css": "text/css" };

let server;
let port;
before(async () => {
  server = createServer((req, res) => {
    const path = normalize(join(ui, new URL(req.url, "http://x").pathname));
    if (!path.startsWith(ui) || !existsSync(path)) {
      res.writeHead(404).end();
      return;
    }
    res.writeHead(200, { "content-type": types[extname(path)] ?? "application/octet-stream" });
    res.end(readFileSync(path));
  });
  await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve));
  port = server.address().port;
});
after(() => server.close());

async function measure(query) {
  assert.ok(chrome, "no Chrome found: install Chrome/Chromium or set CHROME to its path");
  const url = `http://127.0.0.1:${port}/tests/browser/scrollbar-probe.html?${query}`;
  const { stdout: dom } = await run(
    chrome,
    [
      "--headless",
      "--no-sandbox",
      "--disable-gpu",
      "--window-size=800,700",
      "--virtual-time-budget=4000",
      "--dump-dom",
      url,
    ],
    { encoding: "utf8", timeout: 30000 },
  );
  const text = dom.match(/<pre id="result">([\s\S]*?)<\/pre>/)[1];
  return JSON.parse(text.replaceAll("&quot;", '"').replaceAll("&amp;", "&"));
}

for (const theme of ["light", "dark"]) {
  test(`${theme}: overflowing tracks scroll and the indicator has an opaque rail above the canvas`, async () => {
    const result = await measure(`theme=${theme}`);
    assert.equal(result.scrollY, 100);
    assert.equal(result.nativeScrollbar, "none");
    assert.ok(result.thumb.width >= 6);
    assert.ok(result.rail.width > result.thumb.width, "thumb needs a contrasting rail");
    assert.ok(result.rail.zIndex > 0, "rail must paint above the waveform canvases");
    assert.ok(!result.rail.background.includes("rgba"), "waveform must not show through the rail");
    assert.ok(result.thumb.x >= result.rail.x);
    assert.ok(result.thumb.x + result.thumb.width <= result.rail.x + result.rail.width);
    assert.ok(result.thumb.height > 0);
  });
}
