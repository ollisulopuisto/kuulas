/** The synonyms of one command id ([] when it has none). */
export function synonymsFor(id) {
  if (SYNONYMS[id]) return SYNONYMS[id];
  const prefix = Object.keys(PREFIX_SYNONYMS).find((p) => id.startsWith(p));
  return prefix ? PREFIX_SYNONYMS[prefix] : [];
}
